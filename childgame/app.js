  function makePairConnect(items, leftKey, rightKey) {
    var left = [];
    var rightSrc = [];
    for (var p = 0; p < items.length; p++) {
      left.push({
        pair: p,
        text: items[p][leftKey],
        emoji: leftKey === "emoji" ? items[p].emoji : "",
        word: leftKey === "emoji" ? items[p].word || items[p].ch || "" : "",
      });
      rightSrc.push({
        pair: p,
        text: items[p][rightKey],
        emoji: rightKey === "emoji" ? items[p].emoji : "",
        word: rightKey === "emoji" ? items[p].word || items[p].ch || "" : "",
      });
    }
    if (leftKey !== "emoji") {
      left.forEach(function (item) {
        item.emoji = "";
      });
    }
    if (rightKey !== "emoji") {
      rightSrc.forEach(function (item) {
        item.emoji = "";
      });
    }
    left = shuffle(left);
    return { left: left, right: shuffle(rightSrc) };
  }

