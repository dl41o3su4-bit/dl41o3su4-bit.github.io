  function makeMoreQuestions() {
    var qs = [];
    var equalAt = [randInt(0, 3), randInt(4, 6), randInt(7, 9)];
    var prevKey = "";
    for (var i = 0; i < 10; i++) {
      var isEqual = equalAt.indexOf(i) !== -1;
      var left = 1;
      var right = 1;
      var tries = 0;
      do {
        if (isEqual) {
          left = right = randInt(1, 10);
        } else {
          var lo = randInt(1, 10);
          var diff = randInt(1, 3);
          var hi = lo + diff;
          if (hi > 10) {
            hi = lo;
            lo = hi - diff;
            if (lo < 1) {
              lo = 1;
              hi = Math.min(10, lo + diff);
            }
          }
          if (lo === hi && hi < 10) hi += 1;
          if (lo === hi && lo > 1) lo -= 1;
          if (Math.random() < 0.5) {
            left = lo;
            right = hi;
          } else {
            left = hi;
            right = lo;
          }
        }
        tries += 1;
      } while (left + ":" + right === prevKey && tries < 10);
      prevKey = left + ":" + right;
      qs.push({
        left: left,
        right: right,
        equal: left === right,
        answer: left === right ? "same" : left > right ? "left" : "right",
        icon: pick(FRUITS.concat(ANIMALS)),
      });
    }
    return qs;
  }

